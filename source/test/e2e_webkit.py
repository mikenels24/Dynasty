import asyncio, subprocess, sys, json
from playwright.async_api import async_playwright
srv = subprocess.Popen([sys.executable, '-m', 'http.server', '8767', '-d', 'dist/site'], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
async def main():
    async with async_playwright() as p:
        b = await p.webkit.launch()
        ctx = await b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, has_touch=True)
        pg = await ctx.new_page()
        errs = []
        pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' and 'fonts' not in m.text else None)
        await pg.goto('http://localhost:8767/', wait_until='domcontentloaded')
        await pg.wait_for_selector('.habit')
        await pg.screenshot(path='shots/1-empty.png', full_page=True)
        w = '.habit[data-habit=water] [data-act=water-plus]'
        await pg.click(w); await pg.wait_for_timeout(150)
        await pg.click(w); await pg.wait_for_timeout(150)
        await pg.click(w); await pg.wait_for_timeout(300)
        await pg.click('.habit[data-habit=walk] [data-act=toggle]'); await pg.wait_for_timeout(200)
        # rapid double tap on vitamins must end up "done" exactly once (busy guard), not toggled off
        await pg.dblclick('.habit[data-habit=vitamins] [data-act=toggle]'); await pg.wait_for_timeout(400)
        await pg.click('.habit[data-habit=journal] [data-act=toggle]'); await pg.wait_for_timeout(200)
        await pg.click('.habit[data-habit=steps] [data-act=steps]')
        await pg.fill('#steps-in', '999999'); await pg.click('#f button[type=submit]')
        print('steps validation:', await pg.text_content('#err'))
        await pg.fill('#steps-in', '9120'); await pg.click('#f button[type=submit]'); await pg.wait_for_timeout(300)
        await pg.click('.habit[data-habit=read] [data-act=read]')
        await pg.fill('#book-in', 'Atomic Habits'); await pg.fill('#pct-in', '12'); await pg.click('#f button[type=submit]'); await pg.wait_for_timeout(400)
        await pg.screenshot(path='shots/2-logged.png', full_page=False)
        xp = await pg.text_content('.dayxp .big em')
        print('XP today after full day:', xp, '(expected 25+15+10+20+25+25+5 = 125)')
        print('vitamins done:', await pg.get_attribute('.habit[data-habit=vitamins]', 'class'))
        await pg.reload(); await pg.wait_for_selector('.habit')
        print('XP after reload:', await pg.text_content('.dayxp .big em'))
        await pg.wait_for_timeout(2700)
        await pg.click('.tab[data-tab=player]'); await pg.wait_for_timeout(200)
        await pg.screenshot(path='shots/3-player.png', full_page=True)
        await pg.click('.tab[data-tab=quests]'); await pg.wait_for_timeout(200)
        await pg.screenshot(path='shots/4-quests.png', full_page=True)
        await pg.click('.tab[data-tab=log]'); await pg.click('[data-act=log-day][data-off="1"]'); await pg.wait_for_timeout(100)
        await pg.click('.habit[data-habit=walk] [data-act=toggle]'); await pg.wait_for_timeout(300)
        await pg.screenshot(path='shots/5-log.png', full_page=False)
        await pg.click('.tab[data-tab=season]'); await pg.wait_for_timeout(200)
        await pg.screenshot(path='shots/6-season.png', full_page=True)
        # backup: grab text, wipe, restore
        bk = await pg.evaluate("() => JSON.stringify({app:'dynasty',version:1,records:[]})")
        data = await pg.evaluate("""() => new Promise(r => { const q = indexedDB.open('dynasty'); q.onsuccess = () => { const t = q.result.transaction('records'); const g = t.objectStore('records').getAll(); g.onsuccess = () => r(g.result); }; })""")
        print('records stored:', len(data), sorted(x['key'].split(':')[0] for x in data))
        full = json.dumps({'app': 'dynasty', 'version': 1, 'records': data})
        await pg.click('[data-act=restore]'); await pg.fill('#bk-paste', bk); await pg.click('#go'); await pg.wait_for_timeout(300)
        await pg.click('.tab[data-tab=gameday]'); print('XP after empty restore:', await pg.text_content('.dayxp .big em'))
        await pg.click('.tab[data-tab=season]'); await pg.click('[data-act=restore]'); await pg.fill('#bk-paste', full); await pg.click('#go'); await pg.wait_for_timeout(300)
        await pg.click('.tab[data-tab=gameday]'); print('XP after full restore:', await pg.text_content('.dayxp .big em'))
        print('bug:', (await pg.text_content('.bug')).strip())
        sw = await pg.evaluate("() => navigator.serviceWorker && navigator.serviceWorker.getRegistrations().then(r => r.length)")
        print('service workers:', sw)
        print('errors:', errs)
        await b.close()
asyncio.run(main()); srv.terminate()
